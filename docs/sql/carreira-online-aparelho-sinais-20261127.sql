-- Um escritor por conta/carreira. A presença existente renova a autorização, sem novo heartbeat de canal.
create table public.esc_carr_aparelho (
 sala uuid not null references public.esc_carr_sala(id) on delete cascade,
 user_id uuid not null, token uuid not null, ate timestamptz not null,
 primary key(sala,user_id)
);
alter table public.esc_carr_aparelho enable row level security;
revoke all on public.esc_carr_aparelho from public,anon,authenticated;
create or replace function public.esc_carr_aparelho(p_sala uuid,p_token uuid,p_entrar boolean default false,p_sair boolean default false)
returns text language plpgsql security definer set search_path=public as $$
declare a public.esc_carr_aparelho%rowtype;
begin
 if auth.uid() is null or p_token is null or not public.esc_carr_sou_membro(p_sala) then return 'sem_permissao'; end if;
 perform pg_advisory_xact_lock(hashtextextended(p_sala::text||auth.uid()::text,0));
 select * into a from public.esc_carr_aparelho where sala=p_sala and user_id=auth.uid() for update;
 if p_sair then
  delete from public.esc_carr_aparelho where sala=p_sala and user_id=auth.uid() and token=p_token;
  return 'ok';
 end if;
 if a.token is distinct from p_token and a.ate>clock_timestamp() then return 'ocupado'; end if;
 if (a.token is distinct from p_token or a.ate<=clock_timestamp()) and not p_entrar then return 'reabrir'; end if;
 insert into public.esc_carr_aparelho values(p_sala,auth.uid(),p_token,clock_timestamp()+interval '180 seconds')
 on conflict(sala,user_id) do update set token=excluded.token,ate=excluded.ate;
 return 'ok';
end $$;
create or replace function public.esc_carr_aparelho_confere(p_sala uuid,p_token uuid)
returns boolean language sql volatile security definer set search_path=public as $$
 select exists(select 1 from public.esc_carr_aparelho where sala=p_sala and user_id=auth.uid() and token=p_token and ate>clock_timestamp() for update)
$$;
-- Escrita privada passa por função: um envio atrasado do aparelho anterior não passa depois de liberar a carreira.
create or replace function public.esc_carr_privado_guarda(p_sala uuid,p_token uuid,p_dados jsonb)
returns text language plpgsql security definer set search_path=public as $$
begin
 if not public.esc_carr_aparelho_confere(p_sala,p_token) then return 'outro_aparelho'; end if;
 if jsonb_typeof(p_dados) is distinct from 'object' or pg_column_size(p_dados)>4194304 then return 'grande_demais'; end if;
 perform set_config('co2.aparelho',p_token::text,true);
 insert into public.esc_carr_privado(sala,user_id,dados,atualizado_em) values(p_sala,auth.uid(),p_dados,clock_timestamp())
 on conflict(sala,user_id) do update set dados=excluded.dados,atualizado_em=excluded.atualizado_em;
 return 'ok';
end $$;
create or replace function public.esc_carr_privado_trava_aparelho() returns trigger language plpgsql security definer set search_path=public as $$
begin
 if exists(select 1 from public.esc_carr_aparelho where sala=new.sala and user_id=new.user_id and ate>clock_timestamp()
 and token::text is distinct from current_setting('co2.aparelho',true)) then raise exception 'carreira_aberta_em_outro_aparelho'; end if;
 return new;
end $$;
create trigger carr_privado_aparelho before insert or update on public.esc_carr_privado for each row execute function public.esc_carr_privado_trava_aparelho();

-- O canal transporta apenas avisos. Autor/ordem e conteúdo vêm do banco autenticado.
create table public.esc_carr_sinal (
 sala uuid not null references public.esc_carr_sala(id) on delete cascade,
 pedido uuid not null, seq bigint generated by default as identity, autor uuid not null,
 tipo text not null check(tipo in ('acao','estado')), dados jsonb not null,
 em timestamptz not null default clock_timestamp(), primary key(sala,pedido)
);
create index carr_sinal_ordem on public.esc_carr_sinal(sala,tipo,seq);
create unique index carr_sinal_estado_unico on public.esc_carr_sinal(sala) where tipo='estado';
alter table public.esc_carr_sinal enable row level security;
revoke all on public.esc_carr_sinal from public,anon,authenticated;
create or replace function public.esc_carr_sinal_envia(p_sala uuid,p_token uuid,p_pedido uuid,p_tipo text,p_dados jsonb)
returns text language plpgsql security definer set search_path=public as $$
declare actor integer;s public.esc_carr_sala%rowtype;
begin
 if not public.esc_carr_sou_membro(p_sala) or not public.esc_carr_aparelho_confere(p_sala,p_token) then return 'sem_permissao'; end if;
 if p_pedido is null or p_tipo not in ('acao','estado') or jsonb_typeof(p_dados) is distinct from 'object' or pg_column_size(p_dados)>524288 then return 'invalido'; end if;
 if exists(select 1 from public.esc_carr_sinal where sala=p_sala and pedido=p_pedido and autor=auth.uid()) then return 'ok'; end if;
 select * into s from public.esc_carr_sala where id=p_sala;
 if p_tipo='estado' then
  if not public.esc_carr_sou_comandante(p_sala) or jsonb_typeof(p_dados->'z') is distinct from 'string' then return 'sem_permissao'; end if;
  insert into public.esc_carr_sinal(sala,pedido,autor,tipo,dados) values(p_sala,p_pedido,auth.uid(),p_tipo,p_dados)
   on conflict(sala) where tipo='estado' do update set pedido=excluded.pedido,autor=excluded.autor,dados=excluded.dados,seq=excluded.seq,em=excluded.em;
 else
  select (o.ordinality-1)::integer into actor from jsonb_array_elements_text(s.mundo->'ordem') with ordinality o(uid,ordinality) where o.uid=auth.uid()::text;
  if actor is null or p_dados->>'type' not in ('SUBMIT_ENVELOPE','SUBMIT_TIEBREAK','MONTE_PICK','MONTE_PASS','HOLANDES_PEGAR','PREGAO_ABERTO_LANCE','TOGGLE_RESERVE_LIST','RENEW_CONTRACT','RELEASE_CONTRACT')
   or p_dados->>'mgrId' is distinct from actor::text or pg_column_size(p_dados)>32768 then return 'sem_permissao'; end if;
  insert into public.esc_carr_sinal(sala,pedido,autor,tipo,dados) values(p_sala,p_pedido,auth.uid(),p_tipo,p_dados);
 end if;
 -- Limpeza oportunista só de comandos antigos, sem apagar progresso/fotografia atual.
 delete from public.esc_carr_sinal where sala=p_sala and tipo='acao' and em<clock_timestamp()-interval '3 days';
 return 'ok';
end $$;
create or replace function public.esc_carr_sinais_le(p_sala uuid,p_depois bigint default 0)
returns jsonb language plpgsql stable security definer set search_path=public as $$
begin
 if not public.esc_carr_sou_membro(p_sala) then return null; end if;
 return jsonb_build_object('estado',(select case when public.esc_carr_sou_comandante(p_sala) then to_jsonb(s)-'sala' else jsonb_set(to_jsonb(s)-'sala','{dados}',s.dados-'secreto') end from public.esc_carr_sinal s where sala=p_sala and tipo='estado'),
  'acoes',coalesce((select jsonb_agg(to_jsonb(a)-'sala' order by seq) from (select * from public.esc_carr_sinal where sala=p_sala and tipo='acao' and seq>p_depois and public.esc_carr_sou_comandante(p_sala) order by seq limit 100) a),'[]'::jsonb));
end $$;
revoke all on function public.esc_carr_aparelho(uuid,uuid,boolean,boolean),public.esc_carr_aparelho_confere(uuid,uuid),public.esc_carr_privado_guarda(uuid,uuid,jsonb),public.esc_carr_privado_trava_aparelho(),public.esc_carr_sinal_envia(uuid,uuid,uuid,text,jsonb),public.esc_carr_sinais_le(uuid,bigint) from public,anon,authenticated;
grant execute on function public.esc_carr_aparelho(uuid,uuid,boolean,boolean),public.esc_carr_privado_guarda(uuid,uuid,jsonb),public.esc_carr_sinal_envia(uuid,uuid,uuid,text,jsonb),public.esc_carr_sinais_le(uuid,bigint) to authenticated;
-- Mantém as regras das funções existentes e verifica a autorização do aparelho na mesma transação.
create or replace function public.esc_carr_comando(p_sala uuid,p_token uuid,p_funcao text,p_args jsonb)
returns jsonb language plpgsql security definer set search_path=public as $$
declare f record;a record;expr text='';out jsonb;
begin
 if not public.esc_carr_sou_membro(p_sala) or not public.esc_carr_aparelho_confere(p_sala,p_token) then return to_jsonb('outro_aparelho'::text);end if;
 if p_args->>'p_sala' is distinct from p_sala::text or p_funcao not in ('esc_carr_continuar','esc_carr_encerrar_dia','esc_carr_gaveta','esc_carr_mundo','esc_carr_pronto','esc_carr_comecar','esc_carr_apito','esc_carr_ritmo','esc_carr_virada_salva','esc_carr_jogo_foto','esc_carr_jogo_troca','esc_carr_jogo_comecar','esc_carr_jogo_apito','esc_carr_jogo_ritmo','esc_carr_jogo_lesao') then return to_jsonb('sem_permissao'::text);end if;
 select p.oid,p.proargnames,p.proargtypes into f from pg_proc p where pronamespace='public'::regnamespace and proname=p_funcao;
 if not found then return to_jsonb('indisponivel'::text);end if;
 for a in select f.proargnames[i+1] nome,format_type(f.proargtypes[i],null) tipo from generate_series(0,array_length(f.proargnames,1)-1) i loop
  if not(p_args?a.nome) then continue;end if;
  expr=expr||case when expr='' then '' else ',' end||format('%I => ',a.nome)||case when a.tipo='jsonb' then format('($1->%L)',a.nome) else format('($1->>%L)::%s',a.nome,a.tipo) end;
 end loop;
 execute format('select to_jsonb(public.%I(%s))',p_funcao,expr) into out using p_args;
 return out;
end $$;
revoke all on function public.esc_carr_comando(uuid,uuid,text,jsonb) from public,anon,authenticated;
grant execute on function public.esc_carr_comando(uuid,uuid,text,jsonb) to authenticated;
