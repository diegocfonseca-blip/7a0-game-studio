import { chromium } from 'playwright-core'
import { createServer } from 'vite'
import assert from 'node:assert/strict'
import { mkdirSync } from 'node:fs'
const out = '/tmp/co2-sincronia-20261127'; mkdirSync(out, { recursive: true })
const server = await createServer({ base: '/', cacheDir: '/tmp/co2-ui-cache', server: { host: '127.0.0.1', port: 5494, strictPort: true, hmr: false, watch: null } }); await server.listen()
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox','--disable-dev-shm-usage'] })
const errors = []
try {
  for (const width of [390, 1440]) for (const modo of ['livre', 'dinamica']) {
    const ctx = await browser.newContext({ viewport: { width, height: 950 } }); await ctx.addInitScript(() => localStorage.setItem('bl_lang','pt')); const page = await ctx.newPage()
    await page.route('**/*', r => r.request().url().startsWith('http://127.0.0.1:5494/') ? r.continue() : r.abort()); await page.routeWebSocket('**/*', w => w.close())
    page.on('pageerror', e => { errors.push(e.message); console.log('PAGEERROR',e.stack) })
    page.on('console',m=>{if(m.type()==='error')console.log('BROWSER',m.text())})
    await page.goto(`http://127.0.0.1:5494/scripts/teste-co2-sincronia/?modo=${modo}`)
    await page.waitForFunction(() => !!window.qaState, null, {timeout:90000})
    await page.waitForFunction(() => qaPrivadoFalhou)
    await page.evaluate(() => { qa.falhaPrivado=false; qaGestao(1) })
    await page.waitForFunction(() => qa.privados.includes(1))
    await page.evaluate(() => { qaGestao(2) })
    await page.waitForFunction(() => qa.privados.includes(2))
    assert.equal(await page.evaluate(() => qaState.round),4,'salva gestão sem mudar rodada')
    if (modo === 'livre') {
      await page.getByRole('button', { name: '✅ Estou pronto', exact: true }).click()
      await page.getByRole('status').waitFor()
      assert.equal(await page.evaluate(() => qa.prontos), 0, 'falha não confirma pronto')
      await page.screenshot({ path: `${out}/${modo}-${width}-falha.png`, fullPage: true })
      await page.evaluate(() => { qa.falhaEnvio = false })
      await page.getByRole('button', { name: '✅ Estou pronto', exact: true }).click()
      await page.waitForFunction(() => qa.prontos === 1)
      await page.evaluate(() => qaTodosProntos())
      await page.waitForTimeout(1200)
      assert.equal(await page.evaluate(() => qa.inicios), 0, 'automático desligado espera dono')
    }
    await page.evaluate(() => { qa.falhaEnvio = false; qa.falhaInicio = true })
    await page.getByRole('button', { name: '▶️ Começar agora', exact: true }).click()
    await page.waitForFunction(() => qa.inicios === 1)
    await page.getByRole('status').waitFor()
    await page.evaluate(() => { qa.falhaInicio = false; qa.falhaLeitura = true })
    await page.waitForTimeout(2100)
    await page.getByRole('button', { name: '▶️ Começar agora', exact: true }).click()
    await page.waitForFunction(() => qa.inicios === 2)
    await page.waitForTimeout(200)
    assert.equal(await page.evaluate(() => qa.plays), 0, 'falha de leitura não simula com gavetas vazias')
    await page.evaluate(() => { qa.falhaLeitura = false })
    await page.waitForFunction(() => qa.plays === 1)
    await page.waitForTimeout(1200)
    assert.equal(await page.evaluate(() => qa.plays), 1, 'recuperação inicia uma vez')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'sem transbordar')
    await page.screenshot({ path: `${out}/${modo}-${width}-recuperado.png`, fullPage: true })
    console.log(`✅ ${modo} ${width}: pronto, início, falha de leitura, recuperação sem recarga e rodada única`)
    await ctx.close()
  }
  for (const width of [390,1440]) {
    const ctx=await browser.newContext({viewport:{width,height:950}})
    await ctx.addInitScript(()=>localStorage.setItem('bl_lang','pt'))
    const p=await ctx.newPage();p.on('pageerror',e=>errors.push(e.message))
    await p.route('**/*',r=>r.request().url().startsWith('http://127.0.0.1:5494/')?r.continue():r.abort());await p.routeWebSocket('**/*',w=>w.close())
    await p.goto('http://127.0.0.1:5494/scripts/teste-co2-sincronia/?modo=livre&guest=1')
    await p.waitForFunction(()=>!!window.qaState)
    assert.equal(await p.getByRole('button',{name:'▶️ Começar agora',exact:true}).count(),0,'convidado não comanda')
    await p.getByRole('button',{name:'✅ Estou pronto',exact:true}).click()
    await p.getByRole('status').waitFor();assert.equal(await p.evaluate(()=>qa.prontos),0)
    await p.evaluate(()=>{qa.falhaEnvio=false})
    await p.getByRole('button',{name:'✅ Estou pronto',exact:true}).click()
    await p.waitForFunction(()=>qa.prontos===1)
    await p.evaluate(()=>qaSala({fase:'jogando'}))
    await p.waitForFunction(()=>qa.plays===1)
    assert.equal(await p.evaluate(()=>qaState.youIdx),1,'convidado continua dono do próprio clube')
    await p.screenshot({path:`${out}/convidado-${width}.png`,fullPage:true})
    console.log(`✅ convidado ${width}: pronto, partida e identidade própria; sem botão do dono`)
    await ctx.close()
  }
  assert.deepEqual(errors, [])
} finally { await browser.close(); await server.close() }
