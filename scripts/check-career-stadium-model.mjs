import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const transpile=path=>ts.transpileModule(fs.readFileSync(path,'utf8'),{compilerOptions:{module:ts.ModuleKind.ES2022}}).outputText;
const url=code=>'data:text/javascript;base64,'+Buffer.from(code).toString('base64');
const dataUrl=url(transpile('src/escalacao/estadiodata.ts'));
const source=transpile('src/escalacao/career-stadium-model.ts').replace("'./estadiodata'",JSON.stringify(dataUrl));
const {careerStadiumView}=await import(url(source));
const rules=await import(dataUrl);
const full={inv:Object.fromEntries(rules.STADIUM_SECTORS.map(s=>[s.k,s.cost])),ext:rules.STADIUM_EXTRAS.map(e=>e.k)};
const fixtures={initial:careerStadiumView(undefined,true),works:careerStadiumView({inv:{grama:60,geral:20},ext:[]},true),arena:careerStadiumView(full,true)};
assert.equal(fixtures.initial.capacity.now,0);
assert.equal(fixtures.initial.scene.retractable,false);
assert.equal(fixtures.initial.extras.every(e=>!e.owned&&!e.unlocked),true);
assert.equal(fixtures.arena.capacity.now,78838);
assert.equal(fixtures.arena.extras.length,11);
assert.equal(fixtures.arena.extras.every(e=>e.owned),true);
assert.equal(careerStadiumView(undefined,false).extras.length,5);
assert.equal(careerStadiumView({inv:{},ext:['grama']},false).scene.sectorPercent.grama,100);
assert.equal(careerStadiumView({inv:{cadeiras:80},ext:[]},true).sectors.find(s=>s.key==='cadeiras').nextCost,10);
assert.equal(fixtures.works.scene.sectorPercent.geral,33);
assert.equal(fixtures.works.extras.find(e=>e.key==='refl').unlocked,false);
const snapshot=JSON.stringify(full);careerStadiumView(full,true);assert.equal(JSON.stringify(full),snapshot);
if(process.argv.includes('--fixtures'))console.log(JSON.stringify(fixtures));
else console.log('PASS empty, partial, full, legacy, gates, costs and no save mutation');
