create role anon nologin;
create role authenticated nologin;
create schema auth;
create table auth.users(id uuid primary key,email text);
create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
grant usage on schema auth to authenticated,anon;
grant execute on function auth.uid() to authenticated,anon;
create table public.esc_pyramid_saves(user_id uuid primary key references auth.users(id),save jsonb,updated_at timestamptz default now());
alter table public.esc_pyramid_saves enable row level security;
create policy own_save on public.esc_pyramid_saves to authenticated using (user_id=(select auth.uid())) with check (user_id=(select auth.uid()));
grant select,insert,update,delete on public.esc_pyramid_saves to authenticated;
create table public.esc_fichas_extras(email text primary key,qtd integer);
create table public.esc_salvar_teste(uid uuid primary key references auth.users(id),inicio timestamptz default now());
create table public.esc_saves_lixeira(id bigint generated always as identity primary key,user_id uuid,career jsonb,career_at timestamptz,removido_em timestamptz,apagar_em timestamptz);
create table public.esc_carreiras_barradas(user_id uuid,seed text);
create table public.test_rights(email text primary key,rights jsonb);
create function public.esc_direitos_de(p_email text) returns jsonb language sql stable as $$select coalesce((select rights from public.test_rights where email=p_email),'{"pago":false}'::jsonb)$$;
create function public.esc_nuvem_gratis_limpa() returns integer language sql security definer as $$select 0$$;
