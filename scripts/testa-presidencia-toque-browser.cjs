// Gestos reais do protocolo de toque do Chromium, sem disparar handlers React à mão.
const assert=require('node:assert/strict');
const {chromium}=require('./presidencia-runtime.cjs').loadDependency('playwright');
(async()=>{const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});try{
 const page=await browser.newPage({locale:'pt-BR',viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:2});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/*',r=>r.request().url().startsWith('http://127.0.0.1:4196/')?r.continue():r.abort());
 await page.goto('http://127.0.0.1:4196/7a0-game-studio/qa-presidencia-mapa.html');await page.waitForFunction(()=>!!window.renderScene);
 const client=await page.context().newCDPSession(page);
 const touch=(type,points)=>client.send('Input.dispatchTouchEvent',{type,touchPoints:points.map(([id,x,y])=>({id,x,y,radiusX:2,radiusY:2,force:1}))});
 const zoom=()=>page.locator('[data-map-zoom]').getAttribute('data-map-zoom').then(Number);
 const viewport=page.locator('.pe-map-viewport'),bounds=await viewport.boundingBox();
 const x=bounds.x+bounds.width/2,y=bounds.y+Math.min(bounds.height/2,350),initial=await zoom();
 await touch('touchStart',[[1,x-35,y],[2,x+35,y]]);
 for(let i=1;i<=6;i++)await touch('touchMove',[[1,x-35-i*10,y],[2,x+35+i*10,y]]);
 await touch('touchEnd',[]);
 await page.waitForFunction(z=>Number(document.querySelector('[data-map-zoom]').dataset.mapZoom)>z*1.8,initial);
 assert.ok(await zoom()<=4,'Zoom respeita o limite');
 const before=await page.locator('.pe-map-world').getAttribute('style');
 await touch('touchStart',[[1,x,y]]);
 for(let i=1;i<=5;i++)await touch('touchMove',[[1,x+i*12,y+i*8]]);
 await touch('touchEnd',[]);
 assert.notEqual(await page.locator('.pe-map-world').getAttribute('style'),before,'Arrasto move cenário inteiro');
 await page.setViewportSize({width:844,height:390});
 await page.waitForFunction(()=>document.documentElement.scrollWidth<=innerWidth);
 assert.ok(await viewport.evaluate(n=>n.clientHeight>=380),'Mapa mantém altura útil na horizontal');
 await page.getByRole('button',{name:'VER TUDO',exact:true}).click();
 const fit=await zoom();assert.ok(fit<=1);
 await page.setViewportSize({width:390,height:844});
 await viewport.scrollIntoViewIfNeeded();
 const b=await viewport.boundingBox(),cx=b.x+b.width/2,cy=b.y+Math.min(b.height/2,300);
 // Cancelamento (interrupção do sistema) não deixa um dedo preso no mapa.
 await touch('touchStart',[[1,cx,cy]]);await touch('touchCancel',[]);
 await page.getByRole('button',{name:'Aproximar mapa',exact:true}).click();
 assert.ok(await zoom()>fit);
 const team=s=>['GOL','LAT','LAT','ZAG','ZAG','MEI','MEI','MEI','ATA','ATA','ATA'].map((pos,i)=>({id:s+i,name:s+i,pos}));
 await page.evaluate(state=>window.renderScene(null,state),{context:{id:'touch-field',stadium:{inv:{grama:30,geral:40,cadeiras:90,visitante:120,camarote:150},ext:['cober']},home:team('h'),away:team('a')},minute:20,homeScore:0,awayScore:0,paused:true,finished:false,homeColor:'#1b7a3d',awayColor:'#c2452f'});
 await page.locator('.pe-live>summary').click();await page.getByRole('button',{name:'VISTA DO ESTÁDIO',exact:true}).click();
 const field=page.locator('.pe-live-viewport');await field.scrollIntoViewIfNeeded();
 await page.waitForFunction(()=>[...document.querySelectorAll('.pe-live-world img[data-map-detail]')].some(i=>i.complete&&i.naturalWidth>0));
 const f=await field.boundingBox();assert.ok(f.height>=600,'Campo ocupa área grande no celular');
 const fx=f.x+f.width/2,fy=f.y+f.height/2;
 const initialFieldZoom=Number(await field.getAttribute("data-field-zoom"));
 await touch('touchStart',[[1,fx-30,fy],[2,fx+30,fy]]);
 for(let i=1;i<=5;i++)await touch('touchMove',[[1,fx-30-i*9,fy],[2,fx+30+i*9,fy]]);
 await touch('touchEnd',[]);
 await page.waitForFunction(z=>Number(document.querySelector('[data-field-zoom]').dataset.fieldZoom)>z*1.8,initialFieldZoom);
 assert.ok(await page.locator('.pe-live-world').evaluate(n=>Math.abs(n.offsetWidth/n.offsetHeight-1.5)<.01),'Pinça não distorce o campo');
 await page.getByRole('button',{name:'VER CAMPO',exact:true}).click();
 assert.ok(await field.evaluate(n=>Number(n.dataset.fieldZoom)<1),'Ver campo enquadra a imagem inteira em tela vertical');
 await page.setViewportSize({width:844,height:390});await page.waitForFunction(()=>document.documentElement.scrollWidth<=innerWidth);
 assert.equal(await page.locator('[data-athlete]').count(),22);
 assert.deepEqual(errors,[]);
 console.log('PASS: pinça real no mapa e campo, arrasto, rotação do celular, altura útil, cancelamento e retomada dos controles. Chromium móvel local.');
}finally{await browser.close()}})().catch(e=>{console.error(e);process.exitCode=1});
