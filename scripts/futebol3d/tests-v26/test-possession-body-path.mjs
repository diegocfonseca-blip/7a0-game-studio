import assert from 'node:assert/strict';
import {preparePossessionBodyPath} from '../../../src/escalacao/futebol3d/chibi/possession-body-path.mjs';
const source=t=>({x:t,z:0}),ballAt=t=>({x:t+Math.min(2.2,t),y:.11,z:0});
const sample=t=>({owner:t<3?'runner':null,phase:'dominio',ball:ballAt(t)});
const events=[{kind:'recebe',t:.1,bola:{y:.11}},{kind:'toque',t:2.9,bola:{y:.11}}];
const snapshots=Array.from({length:301},(_,i)=>sample(i/100));
const path=preparePossessionBodyPath(source,sample,'runner',events,{duration:4});
assert(path.sample(2).x>source(2).x+.6,'The receiver goes after a rolling ball that is ahead');
assert(Math.abs(ballAt(2).x-path.sample(2).x)<1,'Keep up after receiving without pulling the ball');
for(const e of events)assert.deepEqual(path.sample(e.t),source(e.t),'Exact calibrated reception/release remains fixed');
for(let t=0;t<=4;t+=.01)assert(Math.hypot(path.sample(t).x-source(t).x,path.sample(t).z-source(t).z)<=2.000001);
assert.deepEqual(Array.from({length:301},(_,i)=>sample(i/100)),snapshots,'Do not mutate the ball, owner or event source');
const unreceived=preparePossessionBodyPath(source,sample,'runner',[],{duration:4});
for(let t=0;t<=4;t+=.05)assert.deepEqual(unreceived.sample(t),source(t),'Ownership alone does not cause a fictitious reception');
const hands=preparePossessionBodyPath(source,sample,'runner',[{...events[0],hands:true}],{duration:4});
assert.deepEqual(hands.sample(2),source(2),'No goalkeeper/hand attachment through this path');
const missed=preparePossessionBodyPath(source,t=>({...sample(t),owner:'opponent'}),'runner',events,{duration:4});
assert.deepEqual(missed.sample(2),source(2),'A missed pass stays free');
console.log('PASS: receiver follows fixed ball after reception; no ball attraction, invented reception or displaced impacts');

const still=()=>({x:0,z:0}),spill=t=>({x:.45+Math.max(0,t-1)*8,y:.11,z:0}),r={kind:'recebe',t:1,bola:{y:.11}};
const early=preparePossessionBodyPath(still,t=>({owner:'runner',phase:'dominio',ball:spill(t)}),'runner',[r],{duration:2});
assert.deepEqual(early.sample(1),still(),'The exact reception remains pinned');
assert(early.sample(1.16).x>.05,'Reach for an escaped first touch before the old 400ms dead period ends');
assert(early.sample(1.3).x>early.sample(1.16).x);
console.log('PASS: early bounded pursuit after reception, without delaying or moving the ball/contact');

const freeBall=t=>({x:t+1.1,y:.11,z:0});
const lossFrame=t=>({owner:t<1?'runner':t<2?'': 'opponent',phase:'dominio',ball:freeBall(t)});
const lossEvents=[{kind:'recebe',t:.1,bola:{y:.11}}];
const loss=preparePossessionBodyPath(source,lossFrame,'runner',lossEvents,{duration:4});
assert(loss.sample(1.2).x>source(1.2).x+.2,'A loose ownership transition must not erase the attempt to recover');
assert(loss.sample(1.8).x>source(1.8).x+.2,'Recovery continues while the ball is loose and reachable');
assert(loss.pursuits.length===1&&loss.pursuits[0].reason==='controlled-by-player');
assert(loss.sample(2.02).x>source(2.02).x+.1,'An opponent taking control does not snap the runner back to his tactical anchor');
assert(loss.sample(3.8).x-source(3.8).x<.01,'Recovery is bounded, not perpetual ball pursuit');
const kicked=preparePossessionBodyPath(source,lossFrame,'runner',[...lossEvents,{kind:'toque',t:.95,bola:{y:.11}}],{duration:4});
assert.equal(kicked.pursuits.length,0,'A deliberate release must never be mistaken for an escaped control');
const restarted=preparePossessionBodyPath(source,t=>({...lossFrame(t),phase:t>=1?'lateral':'dominio'}),'runner',lossEvents,{duration:4});
assert.equal(restarted.pursuits.length,0,'A restart terminates recovery intent');
const instantLoss=preparePossessionBodyPath(source,t=>({...lossFrame(t),owner:t<.1?'runner':null}),'runner',lossEvents,{duration:4});
assert.equal(instantLoss.pursuits.length,0,'Never invent a reception on a missed pass');
console.log('PASS: recover a loose first touch, stop at an opponent/restart/release, and rejoin without snapping or changing the ball');
