import assert from 'node:assert/strict';
import {AnimationClip,QuaternionKeyframeTrack,VectorKeyframeTrack,Quaternion,Vector3} from 'three';
import {capturedArmLayer} from '../../../src/escalacao/futebol3d/chibi/captured-arm-layer.mjs';
const q=t=>new Quaternion().setFromAxisAngle(new Vector3(1,0,0),t).toArray();
const arm=new QuaternionKeyframeTrack('mixamorigRightArm.quaternion',[0,1,2],[...q(0),...q(0),...q(0)]);
const foot=new QuaternionKeyframeTrack('mixamorigRightFoot.quaternion',[0,1,2],[...q(0),...q(.4),...q(0)]);
const hips=new VectorKeyframeTrack('mixamorigHips.position',[0,1,2],[0,1,0,0,.9,0,0,1,0]);
const base=new AnimationClip('passe_chapa',2,[arm,foot,hips]);
const donor=new AnimationClip('passe',1,[new QuaternionKeyframeTrack(arm.name,[0,.5,1],[...q(0),...q(.6),...q(1)])]);
const saved=base.toJSON();
const layered=capturedArmLayer(base,donor,{contact:1,donorContact:.5,rate:.7});
assert.equal(layered.name,base.name);assert.equal(layered.duration,base.duration);
assert.equal(layered.tracks[1],foot,'Exact original striking-limb data must remain shared');
assert.equal(layered.tracks[2],hips,'No root-motion or contact-position changes');
assert.deepEqual(base.toJSON(),saved,'Do not mutate the original imported clip');
const value=layered.tracks[0].createInterpolant().evaluate(1);
assert(new Quaternion().fromArray(value).angleTo(new Quaternion().fromArray(q(.6)))<1e-6,'Donor contact pose aligns with the same official impact');
for(const value of layered.tracks[0].values)assert(Number.isFinite(value));
assert.throws(()=>capturedArmLayer(base,donor,{contact:1,donorContact:.5,rate:0}));
console.log('PASS: captured arm layer preserves striking limb/root and immutable source, with aligned donor pose');
