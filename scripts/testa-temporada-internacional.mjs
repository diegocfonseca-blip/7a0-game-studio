import assert from 'node:assert/strict'
import { createServer } from 'vite'

const vite = await createServer({ server: { middlewareMode: true, hmr: false }, appType: 'custom' })
try {
  const { CATALOG_BOTH } = await vite.ssrLoadModule('/src/escalacao/data.ts')
  const { makeInternationalCampaign } = await vite.ssrLoadModule('/src/escalacao/career-international-season.ts')
  const { summarizeInternationalCampaign } = await vite.ssrLoadModule('/src/escalacao/career-international-summary.ts')
  const { internationalCareerRanking } = await vite.ssrLoadModule('/src/escalacao/career-international-ranking.ts')
  const { pontosDeTitulos } = await vite.ssrLoadModule('/src/escalacao/pyramidseason.tsx')
  const { internationalChoice, internationalQualifiers, isInternationalCareerTester } = await vite.ssrLoadModule('/src/escalacao/career-international.ts')
  const needs = { GOL: 1, LAT: 2, ZAG: 2, MEI: 3, ATA: 3 }
  const xi = Object.entries(needs).flatMap(([pos, count]) => CATALOG_BOTH[pos].slice(0, count).map((card, i) => ({ ...card, pos, id: `minha-${pos}-${i}` })))
  const input = { season: 40, seed: 12345, representedClub: 'Flamengo', userTeam: 'Meu FC', userId: 0, priority: 1, userXI: xi }
  const campaign = makeInternationalCampaign(input)
  assert.equal(campaign.teams.length, 72)
  assert.equal(campaign.teams.filter(t => t.you).length, 1)
  assert.equal(campaign.teams.find(t => t.you)?.name, 'Meu FC')
  assert.equal(campaign.steps.length, 14)
  assert.equal(campaign.libertadoresGroups.length, 6)
  assert.equal(campaign.libertadoresGroups.every(g => g.length === 6 && g.every(t => t.played === 5)), true)
  assert.equal(campaign.championsTable.length, 36)
  assert.equal(campaign.championsTable.every(t => t.played === 8), true)
  assert.equal(campaign.teams.find(t => t.id === campaign.libertadoresChampion)?.competition, 'libertadores')
  assert.equal(campaign.teams.find(t => t.id === campaign.championsChampion)?.competition, 'champions')
  assert.equal([campaign.libertadoresChampion, campaign.championsChampion].includes(campaign.mundialChampion), true)
  const matches = campaign.steps.flatMap(s => [...(s.libertadores?.matches ?? []), ...(s.champions?.matches ?? []), ...(s.mundial?.matches ?? [])])
  assert.equal(campaign.statistics.reduce((n, s) => n + s.games, 0), matches.length * 22)
  assert.equal(campaign.statistics.reduce((n, s) => n + s.goals, 0), matches.reduce((n, m) => n + m.hg + m.ag, 0))
  assert.equal(campaign.statistics.reduce((n, s) => n + s.assists, 0), matches.flatMap(m => m.goals).filter(g => g.assist).length)
  assert.deepEqual(makeInternationalCampaign(input), campaign)
  const summary = summarizeInternationalCampaign(campaign)
  assert.equal(summary.season, 40)
  assert.equal(summary.representedClub, 'Flamengo')
  assert.equal(summary.games, matches.filter(m => m.home === 'Flamengo' || m.away === 'Flamengo').length)
  assert.equal(summary.playerStats.length, 11)
  assert.equal(summary.teamRecords.length, 72)
  assert.equal(summary.teamRecords.reduce((n, row) => n + row.games, 0), matches.length * 2)
  assert.equal(summary.botPlayerStats.length, campaign.statistics.filter(row => !row.you).length)
  assert.equal(summary.botPlayerStats.reduce((n, row) => n + row[2], 0) + summary.playerStats.reduce((n, row) => n + row.games, 0), matches.length * 22)
  assert.ok(Buffer.byteLength(JSON.stringify(summary)) < 100_000, 'histórico por temporada deve permanecer compacto para o save local')
  const reopened = JSON.parse(JSON.stringify({ seasonNo: 40, careerInternational: { ...campaign, reveal: 7 }, careerInternationalHistory: [] }))
  assert.equal(reopened.careerInternational.reveal, 7)
  assert.deepEqual(summarizeInternationalCampaign(reopened.careerInternational), summary)
  const nextSeason = { ...reopened, seasonNo: 41, careerInternational: null, careerInternationalHistory: [summary] }
  assert.equal(nextSeason.careerInternationalHistory[0].botPlayerStats.length, summary.botPlayerStats.length)
  const rank = internationalCareerRanking(nextSeason.careerInternationalHistory)
  assert.equal(rank.length, 72)
  assert.equal(rank.find(row => row.club === campaign.mundialChampion).mundial, 1)
  assert.equal(rank.reduce((n, row) => n + row.games, 0), matches.length * 2)
  assert.equal(rank.reduce((n, row) => n + row.points, 0), 160) // 🏅 01/10: Mundial 60 + Libertadores 50 + Champions 50
  const oldHistory = [{ ...summary, teamRecords: undefined, botPlayerStats: undefined }]
  assert.equal(internationalCareerRanking(oldHistory).find(row => row.club === campaign.libertadoresChampion).libertadores, 1)
  assert.equal(isInternationalCareerTester('diego.c.fonseca@gmail.com'), true)
  assert.equal(isInternationalCareerTester('outra@conta.com'), false)
  const league = Array.from({ length: 20 }, (_, i) => ({ id: i + 1 }))
  const qualifiers = internationalQualifiers(league, league[5], team => String(team.id))
  assert.equal(qualifiers.length, 8)
  assert.equal(qualifiers[1].team.id, 6)
  assert.equal(internationalChoice(true, 39, qualifiers, '1', team => String(team.id)).length, 0)
  assert.equal(internationalChoice(true, 87, qualifiers, '1', team => String(team.id)).length, 72)
  assert.equal(internationalChoice(false, 87, qualifiers, '1', team => String(team.id)).length, 0)
  const nine = internationalQualifiers(league, league[9], team => String(team.id))
  assert.equal(nine.length, 9)
  assert.equal(nine[1].team.id, 10)
  assert.equal([6, 8, 10, 14, 20, 30, 70, 85].includes(summary.prizeCoins), true)
  const botOnly = makeInternationalCampaign({ season: 87, seed: 54321, representedClub: null, userTeam: 'Meu FC', userId: 0, priority: null, userXI: [] })
  assert.equal(botOnly.teams.filter(t => t.you).length, 0)
  assert.equal(botOnly.mundialChampion.length > 0, true)
  assert.equal(summarizeInternationalCampaign(botOnly).prizeCoins, 0)
  assert.equal(summarizeInternationalCampaign(botOnly).botPlayerStats.length, botOnly.statistics.length)
  const century = makeInternationalCampaign({ ...input, season: 100 })
  assert.equal(century.steps.at(-1).mundial.competition, 'mundial')
  assert.equal(century.steps.slice(0, -1).every(step => !step.mundial), true)
  const european = makeInternationalCampaign({ ...input, representedClub: 'Real Madrid' })
  assert.equal(european.teams.find(team => team.you)?.name, 'Meu FC')
  assert.equal(european.teams.find(team => team.you)?.competition, 'champions')
  assert.equal(summarizeInternationalCampaign(european).competition, 'champions')
  assert.equal(european.steps.at(-1).mundial.competition, 'mundial')
  for (const [title, points] of Object.entries({ world: 200, mundial: 60, libertadores: 50, champions: 50, copa: 30 })) {
    assert.equal(pontosDeTitulos({ [title]: 1 }), points, `pontuação local: ${title}`)
  }
  assert.equal(pontosDeTitulos({ world: 1, mundial: 1, libertadores: 1, champions: 1, copa: 1 }), 390)
  console.log('Temporada internacional: 72 elencos, 2 competições, Mundial, estatísticas e pontos locais OK')
} finally {
  await vite.close()
}
